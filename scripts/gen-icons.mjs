// Writes components/icons/glyphs.ts: the inner SVG markup of the Phosphor icons the site uses, only in the weights it
// uses. The full @phosphor-icons/react module ships all six weights of every icon to the browser (~90 KB); this keeps
// the exact same markup at a fraction of the size. Run after adding an icon or a weight: node scripts/gen-icons.mjs
import { writeFileSync } from "node:fs";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as P from "@phosphor-icons/react/ssr";

// name -> [Phosphor component, extra weights besides duotone]
const ICONS = {
  search: ["MagnifyingGlass"], calendar: ["CalendarBlank"], link: ["LinkSimple"], external: ["ArrowSquareOut"],
  close: ["X", ["bold"]], chevronLeft: ["CaretLeft", ["bold"]], chevronRight: ["CaretRight", ["bold"]],
  chevronDown: ["CaretDown", ["bold"]], arrowUp: ["ArrowUp", ["bold"]], arrowLeft: ["ArrowLeft", ["bold"]],
  crown: ["Crown", ["fill"]], medal: ["Medal", ["fill"]], star: ["Star"], pin: ["PushPin"], megaphone: ["Megaphone"],
  images: ["Images"], image: ["Image"], flag: ["Flag"], users: ["UsersThree"], teacher: ["ChalkboardTeacher"],
  info: ["Info"], expand: ["ArrowsOut"], reset: ["ArrowCounterClockwise"], user: ["User"], globe: ["Globe"],
  check: ["Check", ["bold"]], menu: ["List"], mapPin: ["MapPin"], phone: ["Phone"], fax: ["Printer"], buildings: ["Buildings"],
};

const inner = (comp, weight) => renderToStaticMarkup(createElement(P[comp], { weight })).replace(/^<svg[^>]*>|<\/svg>$/g, "");
const lines = Object.entries(ICONS).map(([name, [comp, extra = []]]) => {
  const w = Object.fromEntries(["duotone", ...extra].map((x) => [x, inner(comp, x)]));
  return `  ${name}: ${JSON.stringify(w)},`;
});
writeFileSync("components/icons/glyphs.ts", [
  "// Generated by scripts/gen-icons.mjs from @phosphor-icons/react (MIT) — do not edit by hand.",
  "// Inner markup of a 256x256 viewBox; duotone has the 0.2-opacity layer that globals.css colours pink (.ico).",
  "export const GLYPHS = {",
  ...lines,
  "} as const satisfies Record<string, { duotone: string; bold?: string; fill?: string }>;",
  "",
].join("\n"));
console.log(`components/icons/glyphs.ts: ${Object.keys(ICONS).length} icons`);
